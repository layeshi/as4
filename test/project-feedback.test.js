test('project accounting includes closed projects, groups by asset owner and never invents legacy material records',()=>{
  const {w,a,j} = fixture();
  contributeMaterials(w,j,a.id,35000,5);
  contributeMaterials(w,j,a.id,0,15,{kind:'city'});
  j.contributions[0].refunds = [{beneficiary:{kind:'agent',id:'PRIVATE-HEIR'},energy:1,materials:1}];
  // The records, rather than speeches/gifts or the legacy energy-only actor map, are authoritative.
  j.contributors[a.id] = 999999;
  spendProject(w,j,j.needWork);
  j.status = 'built'; j.phase = 'built';
  const before = stateHash(w);
  const detail = materialLook(w,'project',{id:j.id},a.id);
  assert.equal(detail.status,'built');
  assert.equal(detail.accounting.contributors.find(x=>x.account.id===a.id).energy,35000);
  assert.equal(detail.accounting.contributors.find(x=>x.account.kind==='city').materials,15);
  assert.equal(detail.accounting.contributors.find(x=>x.account.id===a.id).materials,5);
  assert.equal(detail.accounting.totals.energy,35000);
  assert.equal(detail.accounting.totals.spentEnergy,35000);
  assert.equal(detail.accounting.totals.spentMaterials,20);
  assert.equal(detail.accounting.escrow.energy,0);
  assert.equal(materialLook(w,'projects')[0].id,j.id);
  assert.ok(!JSON.stringify(detail).includes('PRIVATE-'));
  assert.equal(stateHash(w),before);
  j.status = 'open'; j.phase = 'funding';
  terminateProject(w,j,'cancelled');
  assert.equal(materialLook(w,'project',{id:j.id}).accounting.escrow.materials,0);
  assert.equal(materialLook(w,'project',{id:j.id}).accounting.totals.materials,20);
  delete j.contributions;
  assert.equal(materialLook(w,'project',{id:j.id}).accounting.recordsAvailable,false);
  assert.throws(()=>materialLook(w,'project',{}),e=>e.code==='invalid_args');
  assert.throws(()=>materialLook(w,'project',{id:'missing'}),e=>e.code==='not_found');
  assert.deepEqual(materialLook(w,'projects',{after:j.id,limit:1}),[]);
});
test('project contributor pages retain full totals and deterministic cursors without missing material-only accounts',()=>{
  const {w,a,j} = fixture();
  for(let n=1;n<=12;n++) contributeMaterials(w,j,a.id,n,1,{kind:'agent',id:`a${n}`});
  const first=materialLook(w,'project',{id:j.id,limit:5}).accounting;
  const second=materialLook(w,'project',{id:j.id,limit:5,after:first.next}).accounting;
  const third=materialLook(w,'project',{id:j.id,limit:5,after:second.next}).accounting;
  assert.deepEqual([...first.contributors,...second.contributors,...third.contributors].map(c=>c.account.id),Array.from({length:12},(_,i)=>`a${i+1}`));
  assert.equal(first.totals.energy,78);
  assert.equal(third.next,null);
  assert.throws(()=>materialLook(w,'project',{id:j.id,limit:51}),e=>e.code==='invalid_args');
  assert.throws(()=>materialLook(w,'projects',{after:''}),e=>e.code==='invalid_args');
});
test('personal construction visibility matches owner/group/public checks and separates phase and location',()=>{
  const {w,a,j} = fixture();
  const b = makeAgent(w,{name:'乙',lang:'zh',soul:'s',kind:'external',energy:100000,coins:0,place:a.place});
  j.phase = 'building'; j.access = 'owner';
  let p = buildPerception(w,b.id,{lang:'zh',ack:false});
  assert.equal(p.here.projects[0].participation.authorized,false);
  assert.equal(p.actions.find(x=>x.type==='construct').available,false);
  assert.match(renderLook(p,'here',undefined,{lang:'zh'}),/仅业主/);
  assert.equal(materialLook(w,'project',{id:j.id},a.id).participation.canAttemptConstruct,true);
  j.access = 'public';
  assert.equal(materialLook(w,'project',{id:j.id},b.id).participation.canAttemptConstruct,true);
  b.place = 'port';
  assert.ok(materialLook(w,'project',{id:j.id},b.id).participation.reasons.includes('wrong_place'));
  j.owner = {kind:'group',id:'g1'}; w.groups.g1 = {name:'社群',steward:a.id}; j.access = 'group'; b.groups = ['g1']; b.place = j.place;
  assert.equal(materialLook(w,'project',{id:j.id},b.id).participation.authorized,true);
  j.access = 'owner';
  assert.equal(materialLook(w,'project',{id:j.id},b.id).participation.authorized,false);
  j.phase = 'funding';
  assert.ok(materialLook(w,'project',{id:j.id},a.id).participation.reasons.includes('project_unfunded'));
});
